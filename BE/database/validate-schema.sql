FROM @Required r
LEFT JOIN sys.tables tb ON tb.name=r.table_name AND tb.schema_id=SCHEMA_ID(N'dbo')
LEFT JOIN sys.columns c ON c.object_id=tb.object_id AND c.name=r.column_name
LEFT JOIN sys.types t ON t.user_type_id=c.user_type_id
WHERE c.column_id IS NULL OR t.name<>r.type_name;
